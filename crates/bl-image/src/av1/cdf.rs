impl Cdfs {
    pub fn new(base_q_idx: i32) -> Box<Cdfs> {
        let q = match base_q_idx {
            ..=20 => 0,
            21..=60 => 1,
            61..=120 => 2,
            _ => 3,
        };
        Box::new(Cdfs {
            y_mode: DEFAULT_INTRA_FRAME_Y_MODE_CDF,
            uv_cfl_not_allowed: DEFAULT_UV_MODE_CFL_NOT_ALLOWED_CDF,
            uv_cfl_allowed: DEFAULT_UV_MODE_CFL_ALLOWED_CDF,
            angle_delta: DEFAULT_ANGLE_DELTA_CDF,
            intrabc: DEFAULT_INTRABC_CDF,
            part_w8: DEFAULT_PARTITION_W8_CDF,
            part_w16: DEFAULT_PARTITION_W16_CDF,
            part_w32: DEFAULT_PARTITION_W32_CDF,
            part_w64: DEFAULT_PARTITION_W64_CDF,
            part_w128: DEFAULT_PARTITION_W128_CDF,
            segment_id: DEFAULT_SEGMENT_ID_CDF,
            tx_8x8: DEFAULT_TX_8X8_CDF,
            tx_16x16: DEFAULT_TX_16X16_CDF,
            tx_32x32: DEFAULT_TX_32X32_CDF,
            tx_64x64: DEFAULT_TX_64X64_CDF,
            txfm_split: DEFAULT_TXFM_SPLIT_CDF,
            filter_intra_mode: DEFAULT_FILTER_INTRA_MODE_CDF,
            filter_intra: DEFAULT_FILTER_INTRA_CDF,
            skip: DEFAULT_SKIP_CDF,
            palette_y_mode: DEFAULT_PALETTE_Y_MODE_CDF,
            palette_uv_mode: DEFAULT_PALETTE_UV_MODE_CDF,
            palette_y_size: DEFAULT_PALETTE_Y_SIZE_CDF,
            palette_uv_size: DEFAULT_PALETTE_UV_SIZE_CDF,
            pal_y2: DEFAULT_PALETTE_SIZE_2_Y_COLOR_CDF,
            pal_y3: DEFAULT_PALETTE_SIZE_3_Y_COLOR_CDF,
            pal_y4: DEFAULT_PALETTE_SIZE_4_Y_COLOR_CDF,
            pal_y5: DEFAULT_PALETTE_SIZE_5_Y_COLOR_CDF,
            pal_y6: DEFAULT_PALETTE_SIZE_6_Y_COLOR_CDF,
            pal_y7: DEFAULT_PALETTE_SIZE_7_Y_COLOR_CDF,
            pal_y8: DEFAULT_PALETTE_SIZE_8_Y_COLOR_CDF,
            pal_uv2: DEFAULT_PALETTE_SIZE_2_UV_COLOR_CDF,
            pal_uv3: DEFAULT_PALETTE_SIZE_3_UV_COLOR_CDF,
            pal_uv4: DEFAULT_PALETTE_SIZE_4_UV_COLOR_CDF,
            pal_uv5: DEFAULT_PALETTE_SIZE_5_UV_COLOR_CDF,
            pal_uv6: DEFAULT_PALETTE_SIZE_6_UV_COLOR_CDF,
            pal_uv7: DEFAULT_PALETTE_SIZE_7_UV_COLOR_CDF,
            pal_uv8: DEFAULT_PALETTE_SIZE_8_UV_COLOR_CDF,
            delta_q: DEFAULT_DELTA_Q_CDF,
            delta_lf: DEFAULT_DELTA_LF_CDF,
            delta_lf_multi: [DEFAULT_DELTA_LF_CDF; 4],
            intra_tx_set1: DEFAULT_INTRA_TX_TYPE_SET1_CDF,
            intra_tx_set2: DEFAULT_INTRA_TX_TYPE_SET2_CDF,
            cfl_sign: DEFAULT_CFL_SIGN_CDF,
            cfl_alpha: DEFAULT_CFL_ALPHA_CDF,
            use_wiener: DEFAULT_USE_WIENER_CDF,
            use_sgrproj: DEFAULT_USE_SGRPROJ_CDF,
            restoration_type: DEFAULT_RESTORATION_TYPE_CDF,
            mv_joint: DEFAULT_MV_JOINT_CDF,
            mv_class: DEFAULT_MV_CLASS_CDF,
            mv_class0_bit: [DEFAULT_MV_CLASS0_BIT_CDF; 2],
            mv_class0_fr: DEFAULT_MV_CLASS0_FR_CDF,
            mv_class0_hp: [DEFAULT_MV_CLASS0_HP_CDF; 2],
            mv_sign: [DEFAULT_MV_SIGN_CDF; 2],
            mv_bit: [DEFAULT_MV_BIT_CDF; 2],
            mv_fr: DEFAULT_MV_FR_CDF,
            mv_hp: [DEFAULT_MV_HP_CDF; 2],
            txb_skip: DEFAULT_TXB_SKIP_CDF[q],
            eob_pt16: DEFAULT_EOB_PT_16_CDF[q],
            eob_pt32: DEFAULT_EOB_PT_32_CDF[q],
            eob_pt64: DEFAULT_EOB_PT_64_CDF[q],
            eob_pt128: DEFAULT_EOB_PT_128_CDF[q],
            eob_pt256: DEFAULT_EOB_PT_256_CDF[q],
            eob_pt512: DEFAULT_EOB_PT_512_CDF[q],
            eob_pt1024: DEFAULT_EOB_PT_1024_CDF[q],
            eob_extra: DEFAULT_EOB_EXTRA_CDF[q],
            dc_sign: DEFAULT_DC_SIGN_CDF[q],
            coeff_base_eob: DEFAULT_COEFF_BASE_EOB_CDF[q],
            coeff_base: DEFAULT_COEFF_BASE_CDF[q],
            coeff_br: DEFAULT_COEFF_BR_CDF[q],
        })
    }
}
