/// Translates `s` into `lang` ("de" for German); falls back to `s`.
pub fn tr<'a>(lang: &str, s: &'a str) -> &'a str {
    if lang.starts_with("de") {
        de(s).unwrap_or(s)
    } else {
        s
    }
}

