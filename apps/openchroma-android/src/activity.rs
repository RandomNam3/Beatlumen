//! `ANativeActivity` entry point and the bridge between the Java UI thread
//! and the app thread (a replacement for `android_native_app_glue`).
//!
//! The NativeActivity callbacks run on the Java UI thread. They translate
//! into [`Cmd`]s that are appended to a queue protected by a mutex; a byte
//! written to a pipe wakes the app thread's `ALooper`. Commands whose
//! pointers become invalid when the callback returns (window and input
//! queue destruction) and `onDestroy` wait until the app thread has
//! processed them, like the glue code does; `onPause` waits up to two
//! seconds so settings are saved. Creation commands are asynchronous: the
//! window/queue stays valid until the matching (synchronous) destroy
//! callback returns, and commands are processed in order.

use crate::ffi::*;
use crate::jni::{self, JniEnv};
use std::collections::VecDeque;
use std::ffi::{c_int, c_void};
use std::sync::{Arc, Condvar, Mutex};

/// Commands for the app thread.
pub enum Cmd {
    WindowCreated(WindowPtr),
    WindowDestroyed,
    WindowResized,
    InputQueueCreated(QueuePtr),
    InputQueueDestroyed,
    Start,
    Resume,
    Pause,
    Stop,
    Focus(bool),
    ConfigChanged,
    LowMemory,
    Destroy,
    // From the Java helper:
    Text(String),
    /// A key generated by the soft keyboard (press + release).
    ImeKey(i32),
    Permission(bool),
    Files(Vec<String>),
}

pub struct WindowPtr(pub *mut ANativeWindow);
pub struct QueuePtr(pub *mut AInputQueue);
// SAFETY: the pointers are handed to the app thread, which is the only
// user; their validity is guaranteed by the synchronous destroy commands.
unsafe impl Send for WindowPtr {}
unsafe impl Send for QueuePtr {}

struct State {
    queue: VecDeque<(u64, Cmd)>,
    next_seq: u64,
    done_seq: u64,
    exited: bool,
}

/// State shared between the UI thread callbacks and the app thread.
pub struct Shared {
    state: Mutex<State>,
    cond: Condvar,
    /// Pipe: the app thread polls `wake_read` in its looper.
    pub wake_read: c_int,
    wake_write: c_int,
}

impl Shared {
    fn new() -> Option<Shared> {
        let mut fds = [0 as c_int; 2];
        // SAFETY: valid out array of two fds.
        if unsafe { pipe2(fds.as_mut_ptr(), O_NONBLOCK | O_CLOEXEC) } != 0 {
            return None;
        }
        Some(Shared {
            state: Mutex::new(State { queue: VecDeque::new(), next_seq: 1, done_seq: 0, exited: false }),
            cond: Condvar::new(),
            wake_read: fds[0],
            wake_write: fds[1],
        })
    }

    fn wake(&self) {
        let b = 1u8;
        // SAFETY: writing one byte to our own pipe; a full pipe (EAGAIN) is
        // fine because the reader is already due to wake up.
        unsafe { write(self.wake_write, &b as *const u8 as *const c_void, 1) };
    }

    /// Queues a command; returns its sequence number.
    pub fn post(&self, cmd: Cmd) -> u64 {
        let seq = {
            let mut st = self.state.lock().unwrap_or_else(|e| e.into_inner());
            let seq = st.next_seq;
            st.next_seq += 1;
            st.queue.push_back((seq, cmd));
            seq
        };
        self.wake();
        seq
    }

    /// Queues a command and waits until the app thread processed it (or
    /// exited).
    pub fn post_sync(&self, cmd: Cmd) {
        let seq = self.post(cmd);
        let mut st = self.state.lock().unwrap_or_else(|e| e.into_inner());
        while st.done_seq < seq && !st.exited {
            st = self.cond.wait(st).unwrap_or_else(|e| e.into_inner());
        }
    }

    /// Like [`Shared::post_sync`] but gives up after `timeout` (used for
    /// pause, which must not block the UI thread for long).
    pub fn post_sync_timeout(&self, cmd: Cmd, timeout: std::time::Duration) {
        let seq = self.post(cmd);
        let deadline = std::time::Instant::now() + timeout;
        let mut st = self.state.lock().unwrap_or_else(|e| e.into_inner());
        while st.done_seq < seq && !st.exited {
            let now = std::time::Instant::now();
            if now >= deadline {
                break;
            }
            st = self.cond.wait_timeout(st, deadline - now).unwrap_or_else(|e| e.into_inner()).0;
        }
    }

    /// App thread: drains the wake pipe and takes all pending commands.
    pub fn take(&self) -> Vec<(u64, Cmd)> {
        let mut buf = [0u8; 64];
        // SAFETY: non-blocking reads into a local buffer.
        while unsafe { read(self.wake_read, buf.as_mut_ptr() as *mut c_void, buf.len()) } > 0 {}
        let mut st = self.state.lock().unwrap_or_else(|e| e.into_inner());
        st.queue.drain(..).collect()
    }

    /// App thread: marks commands up to `seq` as processed.
    pub fn done(&self, seq: u64) {
        let mut st = self.state.lock().unwrap_or_else(|e| e.into_inner());
        st.done_seq = st.done_seq.max(seq);
        self.cond.notify_all();
    }

    /// App thread: the thread is exiting; release all waiters.
    pub fn exited(&self) {
        let mut st = self.state.lock().unwrap_or_else(|e| e.into_inner());
        st.exited = true;
        self.cond.notify_all();
    }
}

impl Drop for Shared {
    fn drop(&mut self) {
        // SAFETY: the fds are owned by this struct.
        unsafe {
            close(self.wake_read);
            close(self.wake_write);
        }
    }
}

/// Per-activity data stored in `ANativeActivity::instance`.
struct Instance {
    shared: Arc<Shared>,
    thread: Option<std::thread::JoinHandle<()>>,
}

/// The shared state of the live activity, for the Java native methods.
static CURRENT: Mutex<Option<Arc<Shared>>> = Mutex::new(None);

/// Posts a command coming from the Java helper to the live activity.
pub fn post_from_java(cmd: Cmd) {
    let cur = CURRENT.lock().unwrap_or_else(|e| e.into_inner()).clone();
    if let Some(s) = cur {
        s.post(cmd);
    }
}

/// A raw activity pointer that may be moved to the app thread.
pub struct ActivityPtr(pub *mut ANativeActivity);
// SAFETY: the activity outlives the app thread (onDestroy joins it).
unsafe impl Send for ActivityPtr {}

/// # Safety
/// Called by the NativeActivity callbacks with the activity pointer
/// passed by the framework.
unsafe fn shared(activity: *mut ANativeActivity) -> Option<Arc<Shared>> {
    if activity.is_null() || (*activity).instance.is_null() {
        return None;
    }
    Some((*((*activity).instance as *const Instance)).shared.clone())
}

unsafe fn post(activity: *mut ANativeActivity, cmd: Cmd) {
    if let Some(s) = shared(activity) {
        s.post(cmd);
    }
}

unsafe fn post_sync(activity: *mut ANativeActivity, cmd: Cmd) {
    if let Some(s) = shared(activity) {
        s.post_sync(cmd);
    }
}

unsafe extern "C" fn on_start(a: *mut ANativeActivity) {
    post(a, Cmd::Start);
}
unsafe extern "C" fn on_resume(a: *mut ANativeActivity) {
    post(a, Cmd::Resume);
}
unsafe extern "C" fn on_save_instance_state(_a: *mut ANativeActivity, out_size: *mut usize) -> *mut c_void {
    // All state lives in the app's storage; nothing to save here.
    if !out_size.is_null() {
        *out_size = 0;
    }
    std::ptr::null_mut()
}
unsafe extern "C" fn on_pause(a: *mut ANativeActivity) {
    // Wait (bounded) so the app has saved its settings before the process
    // may be killed.
    if let Some(s) = shared(a) {
        s.post_sync_timeout(Cmd::Pause, std::time::Duration::from_secs(2));
    }
}
unsafe extern "C" fn on_stop(a: *mut ANativeActivity) {
    post(a, Cmd::Stop);
}
unsafe extern "C" fn on_destroy(a: *mut ANativeActivity) {
    if a.is_null() || (*a).instance.is_null() {
        return;
    }
    let inst = Box::from_raw((*a).instance as *mut Instance);
    (*a).instance = std::ptr::null_mut();
    inst.shared.post_sync(Cmd::Destroy);
    if let Some(t) = inst.thread {
        let _ = t.join();
    }
    let mut cur = CURRENT.lock().unwrap_or_else(|e| e.into_inner());
    if cur.as_ref().map(|c| Arc::ptr_eq(c, &inst.shared)).unwrap_or(false) {
        *cur = None;
    }
}
unsafe extern "C" fn on_window_focus_changed(a: *mut ANativeActivity, focused: c_int) {
    post(a, Cmd::Focus(focused != 0));
}
unsafe extern "C" fn on_native_window_created(a: *mut ANativeActivity, w: *mut ANativeWindow) {
    // Asynchronous: the window stays valid until onNativeWindowDestroyed
    // returns, which waits for this command (FIFO) and its release.
    post(a, Cmd::WindowCreated(WindowPtr(w)));
}
unsafe extern "C" fn on_native_window_resized(a: *mut ANativeActivity, _w: *mut ANativeWindow) {
    post(a, Cmd::WindowResized);
}
unsafe extern "C" fn on_native_window_redraw_needed(a: *mut ANativeActivity, _w: *mut ANativeWindow) {
    post(a, Cmd::WindowResized);
}
unsafe extern "C" fn on_native_window_destroyed(a: *mut ANativeActivity, _w: *mut ANativeWindow) {
    post_sync(a, Cmd::WindowDestroyed);
}
unsafe extern "C" fn on_input_queue_created(a: *mut ANativeActivity, q: *mut AInputQueue) {
    // Asynchronous for the same reason as window creation.
    post(a, Cmd::InputQueueCreated(QueuePtr(q)));
}
unsafe extern "C" fn on_input_queue_destroyed(a: *mut ANativeActivity, _q: *mut AInputQueue) {
    post_sync(a, Cmd::InputQueueDestroyed);
}
unsafe extern "C" fn on_content_rect_changed(a: *mut ANativeActivity, _r: *const ARect) {
    post(a, Cmd::WindowResized);
}
unsafe extern "C" fn on_configuration_changed(a: *mut ANativeActivity) {
    post(a, Cmd::ConfigChanged);
}
unsafe extern "C" fn on_low_memory(a: *mut ANativeActivity) {
    post(a, Cmd::LowMemory);
}

/// Entry point called by `android.app.NativeActivity` on the UI thread
/// after loading `libbeatlumen.so`.
///
/// # Safety
/// Called by the framework with a valid activity whose callbacks struct
/// may be filled in.
#[no_mangle]
pub unsafe extern "C" fn ANativeActivity_onCreate(activity: *mut ANativeActivity, _saved_state: *mut c_void, _saved_size: usize) {
    if activity.is_null() {
        return;
    }
    crate::install_panic_hook();
    let a = &mut *activity;
    let cb = &mut *a.callbacks;
    cb.onStart = Some(on_start);
    cb.onResume = Some(on_resume);
    cb.onSaveInstanceState = Some(on_save_instance_state);
    cb.onPause = Some(on_pause);
    cb.onStop = Some(on_stop);
    cb.onDestroy = Some(on_destroy);
    cb.onWindowFocusChanged = Some(on_window_focus_changed);
    cb.onNativeWindowCreated = Some(on_native_window_created);
    cb.onNativeWindowResized = Some(on_native_window_resized);
    cb.onNativeWindowRedrawNeeded = Some(on_native_window_redraw_needed);
    cb.onNativeWindowDestroyed = Some(on_native_window_destroyed);
    cb.onInputQueueCreated = Some(on_input_queue_created);
    cb.onInputQueueDestroyed = Some(on_input_queue_destroyed);
    cb.onContentRectChanged = Some(on_content_rect_changed);
    cb.onConfigurationChanged = Some(on_configuration_changed);
    cb.onLowMemory = Some(on_low_memory);

    let env = JniEnv(a.env);
    if !crate::java::register_natives(env, a.clazz) {
        log(ANDROID_LOG_ERROR, "RegisterNatives failed (is the Java helper class present?)");
    }

    let Some(shared) = Shared::new() else {
        log(ANDROID_LOG_ERROR, "pipe2 failed; cannot start");
        ANativeActivity_finish(activity);
        return;
    };
    let shared = Arc::new(shared);
    *CURRENT.lock().unwrap_or_else(|e| e.into_inner()) = Some(shared.clone());
    let thread_shared = shared.clone();
    let ptr = ActivityPtr(activity);
    let thread = std::thread::Builder::new().name("beatlumen-main".into()).spawn(move || {
        let ptr = ptr;
        let vm = (*ptr.0).vm;
        let env = jni::attach_current_thread(vm);
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| match env {
            Some(env) => crate::main_loop::run(ptr.0, env, &thread_shared),
            None => log(ANDROID_LOG_ERROR, "AttachCurrentThread failed"),
        }));
        if result.is_err() {
            log(ANDROID_LOG_ERROR, "app thread panicked; finishing the activity");
            ANativeActivity_finish(ptr.0);
        }
        if env.is_some() {
            jni::detach_current_thread(vm);
        }
        thread_shared.exited();
    });
    match thread {
        Ok(t) => {
            let inst = Box::new(Instance { shared, thread: Some(t) });
            a.instance = Box::into_raw(inst) as *mut c_void;
        }
        Err(e) => {
            log(ANDROID_LOG_ERROR, &format!("cannot spawn the app thread: {e}"));
            ANativeActivity_finish(activity);
        }
    }
}
